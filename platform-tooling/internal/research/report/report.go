func EnsureModelCatalog(path string, jobs []planner.BenchmarkJob) error {
	if strings.TrimSpace(path) == "" {
		return fmt.Errorf("benchmark model catalog path is required")
	}
	if _, err := os.Stat(path); err == nil {
		return nil
	} else if !os.IsNotExist(err) {
		return fmt.Errorf("stat benchmark model catalog %s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return fmt.Errorf("create benchmark model catalog dir: %w", err)
	}
	unique := map[string]struct{}{}
	models := make([]string, 0, len(jobs))
	for _, job := range jobs {
		model := strings.TrimSpace(job.Model)
		if model == "" {
			continue
		}
		if _, ok := unique[model]; ok {
			continue
		}
		unique[model] = struct{}{}
		models = append(models, model)
	}
	sort.Strings(models)

	file, err := os.Create(path)
	if err != nil {
		return fmt.Errorf("create benchmark model catalog %s: %w", path, err)
	}
	defer file.Close()

	writer := csv.NewWriter(file)
	defer writer.Flush()
	if err := writer.Write([]string{"llm_model", "display_name", "size_bucket", "size_label", "tier", "comparison_status", "notes"}); err != nil {
		return fmt.Errorf("write benchmark model catalog header: %w", err)
	}
	for _, model := range models {
		if err := writer.Write([]string{model, model, "unknown", "n/a", "research", "unclassified", "generated by researchctl"}); err != nil {
			return fmt.Errorf("write benchmark model catalog row %q: %w", model, err)
		}
	}
	writer.Flush()
	if err := writer.Error(); err != nil {
		return fmt.Errorf("flush benchmark model catalog %s: %w", path, err)
	}
	return nil
}

func GenerateBenchmarkReport(ctx context.Context, workspaceRoot, projectFolder, inputFile, summaryPath, modelCatalogPath, reportOut string) error {
	return runContractsCommand(ctx, workspaceRoot, "hilbert-benchmark-report",
		"-project-folder", projectFolder,
		"-cases-file", inputFile,
		"-summary", summaryPath,
		"-model-catalog", modelCatalogPath,
		"-out", reportOut,
	)
}

