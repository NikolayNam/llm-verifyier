func runContractsCommand(ctx context.Context, workspaceRoot, subcommand string, args ...string) error {
	goBinary, err := exec.LookPath("go")
	if err != nil {
		return fmt.Errorf("locate go binary: %w", err)
	}
	toolingRoot := filepath.Join(workspaceRoot, "platform-tooling")
	commandArgs := append([]string{"-C", toolingRoot, "run", "./cmd/contracts", subcommand}, args...)
	cmd := exec.CommandContext(ctx, goBinary, commandArgs...)
	cmd.Env = append(os.Environ(), fmt.Sprintf("%s=%s", toolingpath.WorkspaceRootEnvKey, workspaceRoot))
	output, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("run contracts %s: %w\n%s", subcommand, err, strings.TrimSpace(string(output)))
	}
	return nil
}
